import prisma from "../../../prisma.js";
import { logger } from "../../../config/logger.js";
import { getNextWorkOrderNumber, formatWorkOrderNumber } from "../utils/numeracion.js";
import { listDueCycles, buildCycleKey } from "./dates.js";

export async function generateForPlan(plan, { now, dryRun = false, trigger = "SCHEDULER" } = {}) {
  const result = {
    planId: plan.id,
    plantId: plan.plantId,
    trigger,
    dryRun,
    decision: null,
    cycleKey: null,
    dueAt: null,
    workOrderId: null,
    missedCycles: 0,
    detail: {},
  };

  try {
    return await prisma.$transaction(async (tx) => {
      if (!dryRun) {
        await tx.$executeRawUnsafe(
          `SELECT pg_advisory_xact_lock($1)`,
          plan.id
        );
      }

      const currentPlan = await tx.mtPlan.findUnique({
        where: { id: plan.id },
        include: { tasks: true },
      });

      if (!currentPlan) {
        result.decision = "ERROR";
        result.detail = { error: "Plan not found" };
        return result;
      }

      if (!currentPlan.active || currentPlan.deletedAt) {
        result.decision = "SKIPPED_INACTIVE";
        return result;
      }

      const cycles = listDueCycles(currentPlan, now, currentPlan.leadDays);

      if (!cycles || cycles.length === 0) {
        result.decision = "SKIPPED_NOT_DUE";
        return result;
      }

      const latestCycle = cycles[cycles.length - 1];
      const missedCount = cycles.length - 1;
      result.missedCycles = missedCount;
      result.dueAt = latestCycle.dueAt;

      const cycleKey = buildCycleKey(currentPlan, latestCycle.dueAt, currentPlan.triggerType);
      result.cycleKey = cycleKey;

      if (currentPlan.skipIfOpen) {
        const openWO = await tx.mtWorkOrder.findFirst({
          where: {
            plantId: currentPlan.plantId,
            planId: currentPlan.id,
            status: { notIn: ["FINISHED", "VALIDATED", "REJECTED", "CANCELLED"] },
          },
          select: { id: true, cycleKey: true },
        });

        if (openWO) {
          result.decision = "SKIPPED_OPEN";
          result.detail = { openWorkOrderId: openWO.id, openCycleKey: openWO.cycleKey };

          if (!dryRun) {
            await tx.mtPlan.update({
              where: { id: currentPlan.id },
              data: {
                nextDueAt: latestCycle.dueAt,
                lastGeneratedAt: now,
              },
            });

            await tx.mtPlanRun.create({
              data: {
                plantId: currentPlan.plantId,
                planId: currentPlan.id,
                runAt: now,
                trigger,
                dryRun: false,
                decision: "SKIPPED_OPEN",
                cycleKey,
                dueAt: latestCycle.dueAt,
                missedCycles: missedCount,
                detail: result.detail,
              },
            });
          }

          return result;
        }
      }

      const woNumber = await getNextWorkOrderNumber(currentPlan.plantId);
      const woTitle = `[${currentPlan.code}] ${currentPlan.title}`;

      const defaultStatus = currentPlan.defaultAssigneeId ? "ASSIGNED" : "APPROVED";

      let workOrder;
      try {
        workOrder = await tx.mtWorkOrder.create({
          data: {
            plantId: currentPlan.plantId,
            number: woNumber,
            type: currentPlan.type,
            status: defaultStatus,
            priority: currentPlan.priority,
            assetId: currentPlan.assetId,
            title: woTitle,
            description: currentPlan.description,
            requestedBy: currentPlan.createdBy,
            assignedTo: currentPlan.defaultAssigneeId || null,
            scheduledAt: latestCycle.dueAt,
            dueAt: latestCycle.dueAt,
            planId: currentPlan.id,
            cycleKey,
            estimatedMinutes: currentPlan.estimatedMinutes || null,
            version: 0,
          },
        });
      } catch (err) {
        if (err.code === "P2002" && err.meta?.target?.includes("cycleKey")) {
          result.decision = "SKIPPED_DUPLICATE";
          return result;
        }
        throw err;
      }

      result.workOrderId = workOrder.id;
      result.decision = "GENERATED";

      await tx.mtWorkOrderEvent.create({
        data: {
          workOrderId: workOrder.id,
          plantId: currentPlan.plantId,
          toStatus: defaultStatus,
          userId: currentPlan.createdBy,
          comment: `Generated by ${trigger} scheduler`,
          metadata: {
            source: "SCHEDULER",
            planCode: currentPlan.code,
            cycleKey,
            missedCycles: missedCount,
          },
        },
      });

      for (const task of currentPlan.tasks || []) {
        await tx.mtWorkOrderTask.create({
          data: {
            workOrderId: workOrder.id,
            plantId: currentPlan.plantId,
            position: task.position,
            description: task.description,
            kind: task.kind,
            unit: task.unit,
            minValue: task.minValue,
            maxValue: task.maxValue,
            required: task.required,
            createsCorrectiveOnFail: task.createsCorrectiveOnFail,
          },
        });
      }

      if (!dryRun) {
        await tx.mtPlan.update({
          where: { id: currentPlan.id },
          data: {
            nextDueAt: latestCycle.dueAt,
            lastGeneratedAt: now,
          },
        });

        await tx.mtPlanRun.create({
          data: {
            plantId: currentPlan.plantId,
            planId: currentPlan.id,
            runAt: now,
            trigger,
            dryRun: false,
            decision: "GENERATED",
            cycleKey,
            dueAt: latestCycle.dueAt,
            workOrderId: workOrder.id,
            missedCycles: missedCount,
            detail: {
              workOrderNumber: formatWorkOrderNumber(woNumber),
              assignedTo: currentPlan.defaultAssigneeId,
            },
          },
        });
      }

      return result;
    });
  } catch (err) {
    logger.error(`[generateForPlan] Error for plan ${plan.id}`, err);
    result.decision = "ERROR";
    result.detail = { error: err.message };

    try {
      await prisma.mtPlanRun.create({
        data: {
          plantId: plan.plantId,
          planId: plan.id,
          runAt: now,
          trigger,
          dryRun,
          decision: "ERROR",
          detail: result.detail,
        },
      });
    } catch {}

    return result;
  }
}

export async function generateForAssetMeterReading(asset, { now } = {}) {
  const plans = await prisma.mtPlan.findMany({
    where: {
      assetId: asset.id,
      active: true,
      deletedAt: null,
      triggerType: "METER",
    },
  });

  const results = [];

  for (const plan of plans) {
    const lastReading = await prisma.mtMeterReading.findFirst({
      where: { assetId: asset.id },
      orderBy: { readAt: "desc" },
      select: { value: true, readAt: true },
    });

    if (!lastReading) continue;

    const value = lastReading.value;
    const baseline = plan.meterBaseline || 0;
    const interval = plan.meterIntervalHours || 0;

    if (value >= baseline + interval) {
      const cruzados = Math.floor((value - baseline) / interval);

      for (let i = 0; i < cruzados; i++) {
        const umbral = baseline + (i + 1) * interval;
        const cycleKey = `M:${umbral}`;

        const existing = await prisma.mtWorkOrder.findFirst({
          where: {
            plantId: asset.plantId,
            planId: plan.id,
            cycleKey,
          },
        });

        if (!existing) {
          const result = await generateForPlan(plan, {
            now: lastReading.readAt,
            trigger: "METER_READING",
          });
          results.push(result);
          break;
        }
      }
    }
  }

  return results;
}
